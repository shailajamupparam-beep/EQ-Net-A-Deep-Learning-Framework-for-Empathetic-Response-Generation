    profile["dominant_emotion"] = Counter(recent).most_common(1)[0][0]

    # Infer preferred response length from user message length
    if utterance_len < 20:
        profile["preferred_length"] = "short"
    elif utterance_len > 60:
        profile["preferred_length"] = "long"

    profiles[user_id] = profile
    save_profiles(profiles)
    return profile

