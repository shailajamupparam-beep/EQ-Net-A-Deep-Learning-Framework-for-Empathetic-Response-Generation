tokenizer = BertTokenizer.from_pretrained(cfg.ENCODER_MODEL)

class EQNetDataset(Dataset):

    def __init__(self, csv_path):

        self.df = pd.read_csv(csv_path)

        print("Columns:", self.df.columns.tolist())

        self.df = self.df.fillna("")

    def __len__(self):
        return len(self.df)

    def __getitem__(self, idx):

        row = self.df.iloc[idx]

        utterance = str(row["utterance_clean"])
        response = str(row["utterance"])

        enc = tokenizer(
            utterance,
            padding="max_length",
            truncation=True,
            max_length=cfg.MAX_LEN,
            return_tensors="pt"
        )

        dec = tokenizer(
            response,
            padding="max_length",
            truncation=True,
            max_length=cfg.MAX_LEN,
            return_tensors="pt"
        )

        emotion = MAPS["emotion2id"].get(
            str(row["emotion"]).lower(), 0
        )

        intensity = MAPS["intensity2id"].get(
            str(row["intensity"]).lower(), 0
        )

        strategy = MAPS["strategy2id"].get(
            str(row["strategy"]).lower(), 0
        )

        return {

            "input_ids": enc["input_ids"].squeeze(),

            "attention_mask": enc["attention_mask"].squeeze(),

            "decoder_ids": dec["input_ids"].squeeze(),

            "emotion_label": torch.tensor(emotion),

            "intensity_label": torch.tensor(intensity),

            "strategy_label": torch.tensor(strategy)
        }

def get_dataloaders():
  train_ds = EQNetDataset("/content/eqnet_plus/data/processed/train_proc.csv")
  val_ds = EQNetDataset("/content/eqnet_plus/data/processed/val_proc.csv")
  test_ds = EQNetDataset("/content/eqnet_plus/data/processed/test_proc.csv")


  train_loader = DataLoader(
    train_ds,
    batch_size=cfg.BATCH_SIZE,
    shuffle=True,
    num_workers=0
)

  val_loader = DataLoader(
        val_ds,
        batch_size=cfg.BATCH_SIZE,
        shuffle=False,
        num_workers=0
    )

  test_loader = DataLoader(
        test_ds,
        batch_size=cfg.BATCH_SIZE,
        shuffle=False,
        num_workers=0
    )

  return train_loader, val_loader, test_loader

