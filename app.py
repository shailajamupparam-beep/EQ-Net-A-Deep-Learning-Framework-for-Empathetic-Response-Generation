@app.post("/analyze", response_model=AnalyzeResponse)
async def analyze(req: AnalyzeRequest):
    emotion, intensity, strategy, cause, conf, _, _ = infer_all(req.utterance)
    return AnalyzeResponse(emotion=emotion, intensity=intensity,
                            strategy=strategy, cause=cause, confidence=conf)

@app.post("/respond", response_model=RespondResponse)
async def respond(req: RespondRequest):
    emotion, intensity, strategy, cause, conf, em_id, st_id = infer_all(req.utterance)
    update_profile(req.user_id, emotion, len(req.utterance.split()))
    response = generator.generate_response(req.utterance, em_id, st_id)
    return RespondResponse(response=response, emotion=emotion,
                            intensity=intensity, strategy=cause)

