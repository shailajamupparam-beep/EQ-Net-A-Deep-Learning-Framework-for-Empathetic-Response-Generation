# ── Helper
def encode_utterance(text: str):
    text = clean_text(text)
    enc  = tokenizer(text, max_length=cfg.MAX_LEN, padding="max_length",
                     truncation=True, return_tensors="pt")
    return {k: v.to(cfg.DEVICE) for k, v in enc.items()}

def infer_all(text: str):
    enc = encode_utterance(text)
    with torch.no_grad():
        out = encoder(enc["input_ids"], enc["attention_mask"],
                       enc["token_type_ids"])
    em_id  = out["emotion_logits"].argmax(-1).item()
    in_id  = out["intensity_logits"].argmax(-1).item()
    st_id  = out["empathy_logits"].argmax(-1).item()
    conf   = torch.softmax(out["emotion_logits"], dim=-1).max().item()
    emotion  = MAPS["id2emotion"][str(em_id)]
    intensity= cfg.INTENSITY_LABELS[in_id]
    strategy = cfg.EMPATHY_STRATEGIES[st_id]
    cause    = identify_cause(text)["cause"]
    return emotion, intensity, strategy, cause, conf, em_id, st_id

