    df = df.copy()

    df["utterance_clean"] = df["utterance"].apply(clean_text)

    df["keywords"] = df["utterance_clean"].apply(extract_emotional_keywords)

    df["intensity"] = df["context"].apply(assign_intensity_label)

    df["strategy"] = df.apply(
        lambda row: assign_empathy_strategy(
            row["context"],
            row["intensity"]
        ),
        axis=1
    )

    return df


