bleu = load("sacrebleu")

# Empathy keywords per strategy
EMPATHY_KEYWORDS = {
    "validation":     ["understand", "makes sense", "valid", "feel"],
    "encouragement":  ["believe in you", "keep going", "strong", "you can"],
    "reassurance":    ["alright", "okay", "be fine", "safe"],
    "acknowledgement":["that", "wonderful", "great", "happy for you"],
    "suggestion":     ["try", "maybe", "could", "consider"],
}

def compute_bleu(predictions: list, references: list) -> float:
    """Compute corpus BLEU score."""
    refs_wrapped = [[r] for r in references]
    result = bleu.compute(predictions=predictions, references=refs_wrapped)
    return result["score"]

def compute_perplexity(model, tokenizer, texts: list) -> float:
    """Compute average perplexity on a list of texts."""
    model.eval()
    total_log_prob, total_tokens = 0, 0
    with torch.no_grad():
        for text in texts:
            enc = tokenizer(text, return_tensors="pt").to(cfg.DEVICE)
            out = model(**enc, labels=enc["input_ids"])
            total_log_prob += out.loss.item() * enc["input_ids"].size(-1)
            total_tokens   += enc["input_ids"].size(-1)
    return math.exp(total_log_prob / total_tokens)

def compute_emotion_accuracy(preds: list, true_labels: list) -> dict:
    """Emotion classification accuracy + per-class report."""
    acc = accuracy_score(true_labels, preds)
    report = classification_report(true_labels, preds,
                                      target_names=cfg.EMOTION_LABELS,
                                      zero_division=0, output_dict=True)
    return {"accuracy": acc, "report": report}

def compute_empathy_score(responses: list, strategies: list) -> float:
    """Keyword-based empathy score: fraction of responses containing strategy keywords."""
    score = 0
    for resp, strat in zip(responses, strategies):
        keywords = EMPATHY_KEYWORDS.get(strat, [])
        if any(kw in resp.lower() for kw in keywords):
            score += 1
    return score / len(responses) if responses else 0.0

def full_evaluation(encoder, gen_model, test_loader, gpt_tokenizer):
    """Run all metrics on test set."""
    preds_emotion, true_emotion = [], []
    generated, references, strategies = [], [], []

    encoder.eval(); gen_model.eval()
    with torch.no_grad():
        for i, batch in enumerate(test_loader):
            if i > 50: break  # quick eval subset
            ids  = batch["input_ids"].to(cfg.DEVICE)
            mask = batch["attention_mask"].to(cfg.DEVICE)
            tt   = batch["token_type_ids"].to(cfg.DEVICE)

            out = encoder(ids, mask, tt)
            pred_em = out["emotion_logits"].argmax(-1).cpu().tolist()
            preds_emotion.extend(pred_em)
            true_emotion.extend(batch["emotion_label"].tolist())

    bleu_score    = compute_bleu(generated[:50], references[:50]) if generated else 0
    em_metrics    = compute_emotion_accuracy(preds_emotion, true_emotion)
    empathy_score = compute_empathy_score(generated, strategies)

    print(f"\n{'='*40}")
    print(f"Emotion Accuracy: {em_metrics['accuracy']:.4f}")
    print(f"BLEU Score:       {bleu_score:.2f}")
    print(f"Empathy Score:    {empathy_score:.4f}")
    print(f"{'='*40}")
    return em_metrics, bleu_score, empathy_score

