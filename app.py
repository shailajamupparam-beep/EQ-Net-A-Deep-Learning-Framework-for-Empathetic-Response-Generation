# Trigger words that often precede a causal phrase
CAUSE_TRIGGERS = [
    "because", "since", "as", "due to", "owing to",
    "when", "after", "caused by", "i lost", "i failed",
    "my", "i was", "she", "he"
]

def extract_cause_rule_based(text: str) -> str:
    """Pattern-based cause extraction."""
    text_lower = text.lower()
    for trigger in CAUSE_TRIGGERS:
        idx = text_lower.find(trigger)
        if idx != -1:
            fragment = text[idx:idx+60].strip()
            # Cut at sentence boundary
            fragment = re.split(r"[.!?]", fragment)[0]
            if len(fragment) > 5:
                return fragment
    return "unspecified event"

def extract_cause_spacy(text: str) -> str:
    """SpaCy dependency parsing approach for cause extraction."""
    doc = nlp(text)

    # Look for advcl (adverbial clause) or ccomp (clausal complement)
    for token in doc:
        if token.dep_ in ("advcl", "ccomp", "relcl"):
            subtree = " ".join([t.text for t in token.subtree])
            if len(subtree.split()) > 2:
                return subtree[:80]

    # Fallback: return the subject + verb phrase
    subject, verb = "", ""
    for token in doc:
        if "subj" in token.dep_:
            subject = token.text
        if token.pos_ == "VERB" and not verb:
            verb = token.text
    if subject and verb:
        return f"{subject} {verb}"
    return extract_cause_rule_based(text)

def identify_cause(text: str) -> dict:
    """Main API: returns cause phrase and named entities."""
    doc = nlp(text)
    entities = [(ent.text, ent.label_) for ent in doc.ents]
    cause_phrase = extract_cause_spacy(text)
    return {"cause": cause_phrase, "entities": entities}

