# modules/data_loader.py

import os
from datasets import load_dataset
import pandas as pd
import matplotlib.pyplot as plt
from collections import Counter

# Create folders if they don't exist
os.makedirs("logs", exist_ok=True)
os.makedirs("data/raw", exist_ok=True)


def load_empathetic_dialogues():
    """
    Load EmpatheticDialogues dataset from Hugging Face.
    """

    print("Downloading EmpatheticDialogues dataset...")

    try:
        dataset = load_dataset("empathetic_dialogues")

        train_df = dataset["train"].to_pandas()
        val_df = dataset["validation"].to_pandas()
        test_df = dataset["test"].to_pandas()

        print(f"Train: {len(train_df)}")
        print(f"Validation: {len(val_df)}")
        print(f"Test: {len(test_df)}")

        return train_df, val_df, test_df

    except Exception as e:
        print("Error while downloading dataset:")
        print(e)
        return None, None, None


def explore_dataset(df, split_name="Train"):
    """
    Perform basic EDA on dataset.
    """

    if df is None:
        print("Dataset not loaded.")
        return

    print("\n===============================")
    print(f"{split_name} Dataset")
    print("===============================")

    print("\nColumns:")
    print(df.columns.tolist())

    print("\nFirst 3 Rows:")
    print(df.head(3))

    # Emotion distribution
    emotion_counts = Counter(df["context"])

    print("\nUnique emotions:", len(emotion_counts))
    print("\nTop 10 emotions:")

    for emotion, count in emotion_counts.most_common(10):
        print(f"{emotion}: {count}")

    # Utterance length
    df["utt_len"] = df["utterance"].astype(str).apply(
        lambda x: len(x.split())
    )

    print("\nAverage utterance length:",
          round(df["utt_len"].mean(), 2))

    print("Maximum length:", df["utt_len"].max())
    print("Minimum length:", df["utt_len"].min())

    # Plotting
    fig, axes = plt.subplots(1, 2, figsize=(15, 5))

    # Emotion distribution
    pd.Series(emotion_counts).sort_values(
        ascending=False
    ).plot(
        kind="bar",
        ax=axes[0],
        color="mediumpurple"
    )

    axes[0].set_title("Emotion Distribution")
    axes[0].set_xlabel("Emotion")
    axes[0].set_ylabel("Count")
    axes[0].tick_params(axis="x", rotation=45)

    # Utterance length
    axes[1].hist(
        df["utt_len"],
        bins=40,
        color="skyblue",
        edgecolor="black"
    )

    axes[1].set_title("Utterance Length Distribution")
    axes[1].set_xlabel("Words")
    axes[1].set_ylabel("Frequency")

    plt.tight_layout()

