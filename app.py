def compute_emotion_accuracy(preds, labels):

    accuracy = accuracy_score(labels, preds)

    report = classification_report(
        labels,
        preds,
        target_names=cfg.EMOTION_LABELS,
        output_dict=True,
        zero_division=0
    )

    return {
        "accuracy": accuracy,
        "report": report
    }


# ===========================================================
# Empathy Score
# ===========================================================

def compute_empathy_score(responses, strategies):

    if len(responses) == 0:
        return 0

    score = 0

    for response, strategy in zip(responses, strategies):

        keywords = EMPATHY_KEYWORDS.get(strategy, [])

        response = response.lower()

        if any(keyword in response for keyword in keywords):
            score += 1

    return score / len(responses)


# ===========================================================
# Response Relevance
# ===========================================================

def compute_response_relevance(predictions, references):

    if len(predictions) == 0:
        return 0

    score = 0

    for pred, ref in zip(predictions, references):

        pred_words = set(pred.lower().split())
        ref_words = set(ref.lower().split())

        if len(ref_words) == 0:
            continue

        overlap = pred_words.intersection(ref_words)

        score += len(overlap) / len(ref_words)

    return score / len(predictions)


