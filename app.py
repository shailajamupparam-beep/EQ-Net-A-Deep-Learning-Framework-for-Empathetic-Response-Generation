import torch
import torch.nn as nn
from transformers import BertModel
from eqnet_plus.modules.intensity_model import IntensityHead
from eqnet_plus.modules.empathy_model import EmpathyHead
from eqnet_plus.config import cfg

class EQNetPlus(nn.Module):
    """
    EQ-Net+: Shared BERT encoder with 3 task heads.
    Emotion Detection | Intensity Estimation | Empathy Strategy
    """
    def __init__(self):
        super().__init__()
        # Shared backbone
        self.bert = BertModel.from_pretrained(cfg.ENCODER_MODEL)
        self.dropout = nn.Dropout(0.3)
        hidden = self.bert.config.hidden_size  # 768

        # Task heads
        self.emotion_head = nn.Sequential(
            nn.Linear(hidden, 256), nn.ReLU(), nn.Dropout(0.2),
            nn.Linear(256, cfg.NUM_EMOTIONS)
        )
        self.intensity_head = IntensityHead(hidden)
        self.empathy_head   = EmpathyHead(hidden)

    def forward(self, input_ids, attention_mask, token_type_ids=None,
               intensity_ids=None):
        # Shared encoding
        bert_out = self.bert(
            input_ids=input_ids,
            attention_mask=attention_mask,
            token_type_ids=token_type_ids
        )
        cls_emb = self.dropout(bert_out.last_hidden_state[:, 0, :])

        # Individual heads
        emotion_logits   = self.emotion_head(cls_emb)
        intensity_logits = self.intensity_head(cls_emb)

        # Empathy head uses predicted intensity if not provided
        if intensity_ids is None:
            intensity_ids = intensity_logits.argmax(dim=-1)
        empathy_logits = self.empathy_head(cls_emb, intensity_ids)

        return {
            "emotion_logits":   emotion_logits,
            "intensity_logits": intensity_logits,
            "empathy_logits":   empathy_logits,
            "cls_emb":          cls_emb
        }


def compute_multitask_loss(outputs, labels):
    """Weighted multi-task loss."""
    ce = nn.CrossEntropyLoss()
    l_emotion   = ce(outputs["emotion_logits"],   labels["emotion"])
    l_intensity = ce(outputs["intensity_logits"], labels["intensity"])
    l_empathy   = ce(outputs["empathy_logits"],   labels["strategy"])

    total = (cfg.LOSS_W_EMOTION   * l_emotion +
             cfg.LOSS_W_INTENSITY * l_intensity +
             cfg.LOSS_W_STRATEGY  * l_empathy)
    return total, l_emotion, l_intensity, l_empathy

