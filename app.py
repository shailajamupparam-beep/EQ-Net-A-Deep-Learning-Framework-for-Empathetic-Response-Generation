# ==============================
def extract_emotional_keywords(text):

    doc = nlp(text)

    keywords = []

    for token in doc:

        if token.pos_ in ["NOUN", "VERB", "ADJ"]:

            if token.text not in STOP_WORDS:

                if len(token.text) > 2:

                    keywords.append(token.lemma_)

    return keywords


# ==============================
# Assign Intensity
# ==============================
def assign_intensity_label(emotion):

    emotion = str(emotion).lower().strip()

    if emotion in HIGH_INTENSITY_EMOTIONS:
        return "high"

    elif emotion in MEDIUM_INTENSITY_EMOTIONS:
        return "medium"

    else:
        return "low"


# ==============================
# Assign Strategy
# ==============================
def assign_empathy_strategy(emotion, intensity):

    emotion = str(emotion).lower()

    if intensity == "high":
        return "validation"

    elif emotion in ["sad", "lonely", "disappointed"]:
        return "encouragement"

    elif emotion in ["anxious", "apprehensive"]:
        return "reassurance"

    elif emotion in ["excited", "hopeful", "grateful"]:
        return "acknowledgement"

    else:
        return "suggestion"


