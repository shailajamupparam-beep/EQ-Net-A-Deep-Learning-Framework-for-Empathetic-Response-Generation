PROFILE_PATH = Path("/content/eqnet_plus/data/processed/user_profiles.json")

def load_profiles() -> dict:
    if PROFILE_PATH.exists():
        with open(PROFILE_PATH) as f:
            return json.load(f)
    return {}

def save_profiles(profiles: dict):
    # Ensure the directory exists before saving the file
    os.makedirs(PROFILE_PATH.parent, exist_ok=True)
    with open(PROFILE_PATH, "w") as f:
        json.dump(profiles, f, indent=2)

def get_or_create_profile(user_id: str) -> dict:
    profiles = load_profiles()
    if user_id not in profiles:
        profiles[user_id] = {
            "emotion_history":    [],
            "preferred_length":   "medium",  # short/medium/long
            "dominant_emotion":   None,
            "interaction_count":  0,
            "last_seen":          str(datetime.now())
        }
        save_profiles(profiles)
    return profiles[user_id]

def update_profile(user_id: str, emotion: str, utterance_len: int):
    profiles = load_profiles()
    profile  = profiles.get(user_id, get_or_create_profile(user_id))

    profile["emotion_history"].append(emotion)
    profile["interaction_count"] += 1
    profile["last_seen"] = str(datetime.now())

    # Update dominant emotion (most frequent in last 10 turns)
    recent = profile["emotion_history"][-10:]
    profile["dominant_emotion"] = Counter(recent).most_common(1)[0][0]

    # Infer preferred response length from user message length
    if utterance_len < 20:
        profile["preferred_length"] = "short"
    elif utterance_len > 60:
        profile["preferred_length"] = "long"

    profiles[user_id] = profile
    save_profiles(profiles)
    return profile

def build_personalized_prompt(utterance: str, user_id: str,
                              emotion: str, strategy: str) -> str:
    """Build enriched prompt for the generator."""
    profile = get_or_create_profile(user_id)
    dominant = profile.get("dominant_emotion", emotion) or emotion
    length   = profile.get("preferred_length", "medium")

    length_hint = {
        "short":  "Reply briefly in 1-2 sentences.",
        "medium": "Reply in 2-3 sentences.",
        "long":   "Reply thoughtfully in 3-5 sentences.",
    }[length]

    prompt = (
        f"[Emotion: {emotion}] [Dominant: {dominant}] [Strategy: {strategy}]\n"
        f"User: {utterance}\n"
        f"Empathetic Assistant ({length_hint}): "
    )
    return prompt

