def train_encoder(model, train_loader, val_loader):
    """Phase A: Train the multi-task encoder."""
    optimizer = optim.AdamW(model.parameters(), lr=cfg.LR, weight_decay=0.01)
    total_steps = len(train_loader) * cfg.EPOCHS
    scheduler = get_linear_schedule_with_warmup(
        optimizer, num_warmup_steps=cfg.WARMUP_STEPS, num_training_steps=total_steps)

    best_val_loss = float("inf")
    for epoch in range(cfg.EPOCHS):
        model.train()
        epoch_loss = 0
        loop = tqdm(train_loader, desc=f"Epoch {epoch+1}/{cfg.EPOCHS}")
        for batch in loop:
            ids  = batch["input_ids"].to(cfg.DEVICE)
            mask = batch["attention_mask"].to(cfg.DEVICE)
            tt   = batch["token_type_ids"].to(cfg.DEVICE)
            int_ids = batch["intensity_label"].to(cfg.DEVICE)
            labels = {
                "emotion":   batch["emotion_label"].to(cfg.DEVICE),
                "intensity": int_ids,
                "strategy":  batch["strategy_label"].to(cfg.DEVICE),
            }
            optimizer.zero_grad()
            outputs = model(ids, mask, tt, int_ids)
            loss, le, li, ls = compute_multitask_loss(outputs, labels)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            optimizer.step()
            scheduler.step()
            epoch_loss += loss.item()
            loop.set_postfix(loss=f"{loss.item():.4f}",
                               emotion=f"{le.item():.3f}",
                               intensity=f"{li.item():.3f}")

        avg_loss = epoch_loss / len(train_loader)
        print(f"\n[Epoch {epoch+1}] Avg Loss: {avg_loss:.4f}")
        if avg_loss < best_val_loss:
            best_val_loss = avg_loss
            torch.save(model.state_dict(), "models/eqnet_encoder_best.pt")
            print("\u2713 Best encoder saved")

def train_decoder(encoder, gen_model, train_loader):
    """Phase B: Train the response generator conditioned on encoder."""
    optimizer = optim.AdamW(gen_model.parameters(), lr=5e-5)
    encoder.eval()
    for epoch in range(3):
        gen_model.train()
        loop = tqdm(train_loader, desc=f"Decoder Epoch {epoch+1}/3")
        for batch in loop:
            ids     = batch["input_ids"].to(cfg.DEVICE)
            mask    = batch["attention_mask"].to(cfg.DEVICE)
            tt      = batch["token_type_ids"].to(cfg.DEVICE)
            dec_ids = batch["decoder_ids"].to(cfg.DEVICE)

            with torch.no_grad():
                enc_out = encoder(ids, mask, tt)
            em_ids = enc_out["emotion_logits"].argmax(dim=-1)
            st_ids = enc_out["empathy_logits"].argmax(dim=-1)

            optimizer.zero_grad()
            loss = gen_model(ids, mask, dec_ids, em_ids, st_ids)
            loss.backward()
            optimizer.step()
            loop.set_postfix(loss=f"{loss.item():.4f}")

    torch.save(gen_model.state_dict(), "models/eqnet_generator_best.pt")
    print("\u2713 Generator saved")

