def full_evaluation(
    encoder,
    generator,
    tokenizer,
    test_loader
):

    encoder.eval()
    generator.eval()

    emotion_predictions = []
    emotion_labels = []

    generated_responses = []
    reference_responses = []
    strategies = []

    with torch.no_grad():

        for batch in test_loader:

            input_ids = batch["input_ids"].to(cfg.DEVICE)

            attention_mask = batch["attention_mask"].to(cfg.DEVICE)

            token_type_ids = batch["token_type_ids"].to(cfg.DEVICE)

            outputs = encoder(
                input_ids,
                attention_mask,
                token_type_ids
            )

            emotion_logits = outputs["emotion_logits"]

            preds = torch.argmax(
                emotion_logits,
                dim=1
            )

            emotion_predictions.extend(
                preds.cpu().numpy().tolist()
            )

            emotion_labels.extend(
                batch["emotion_label"].numpy().tolist()
            )

            # -------------------------
            # Generate Responses
            # -------------------------

            generated_ids = generator.generate(

                input_ids=input_ids,

                attention_mask=attention_mask,

                max_length=60,

                do_sample=True,

                temperature=0.7,

                top_p=0.9,

                pad_token_id=tokenizer.eos_token_id

            )

            preds_text = tokenizer.batch_decode(

                generated_ids,

                skip_special_tokens=True

            )

            refs_text = tokenizer.batch_decode(

                input_ids,

                skip_special_tokens=True

            )

            generated_responses.extend(preds_text)

            reference_responses.extend(refs_text)

            if "strategy" in batch:

                strategies.extend(batch["strategy"])

            else:

                strategies.extend(

                    ["validation"] * len(preds_text)

                )

    emotion_metrics = compute_emotion_accuracy(

        emotion_predictions,

        emotion_labels

    )

    bleu_score = compute_bleu(

        generated_responses,

        reference_responses

    )

    empathy_score = compute_empathy_score(

        generated_responses,

        strategies

    )

    relevance_score = compute_response_relevance(

        generated_responses,

        reference_responses

    )

    perplexity = compute_perplexity(

        generator,

        tokenizer,

        generated_responses
    )

    print("\n")
    print("=" * 60)

    print(f"Emotion Accuracy  : {emotion_metrics['accuracy']:.4f}")

    print(f"BLEU Score        : {bleu_score:.2f}")

    print(f"Perplexity        : {perplexity:.2f}")

    print(f"Empathy Score     : {empathy_score:.4f}")

    print(f"Response Relevance: {relevance_score:.4f}")

    print("=" * 60)

    return {

        "Emotion Accuracy": emotion_metrics["accuracy"],

        "BLEU": bleu_score,

        "Perplexity": perplexity,

        "Empathy Score": empathy_score,

        "Response Relevance": relevance_score,

        "Classification Report": emotion_metrics["report"]

    }

